import { writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const defaultOutput = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../netlify/functions/_shared/deployTarget.generated.ts",
)

const SECRET = /ghp_|github_pat_|bearer\s|postgres:\/\/|-----BEGIN/i

function clean(value) {
  if (typeof value !== "string") return ""
  const trimmed = value.trim()
  if (!trimmed || trimmed.length > 80) return ""
  if (SECRET.test(trimmed)) return ""
  if (!/^[A-Za-z0-9._/-]+$/.test(trimmed)) return ""
  return trimmed
}

const captured = {
  context: clean(process.env.CONTEXT),
  branch: clean(process.env.BRANCH),
  head: clean(process.env.HEAD),
  pullRequest: clean(process.env.PULL_REQUEST),
  reviewId: clean(process.env.REVIEW_ID),
}

const output = process.argv[2] || defaultOutput
const body = `// Generated by scripts/captureDeployTarget.mjs at build time.
// Server-only review metadata. This file contains no credentials.
export const capturedDeployTarget = ${JSON.stringify(captured, null, 2)}
`
writeFileSync(output, body)
